import { describe, expect, it } from 'vitest';
import { isVercelPreviewHost } from './vercel-preview-api-guard.interceptor';

describe('Vercel preview API guard', () => {
  it('identifies branch previews generated by Vercel', () => {
    expect(
      isVercelPreviewHost(
        'comanda-digital-git-fix-dark-chic-1e14b3-matheuz-codes-projects.vercel.app',
      ),
    ).toBe(true);
  });

  it('does not disable API access on production, local development, or unrelated hosts', () => {
    expect(isVercelPreviewHost('comanda-digital-blue.vercel.app')).toBe(false);
    expect(isVercelPreviewHost('localhost')).toBe(false);
    expect(isVercelPreviewHost('dark-chicken.example.com')).toBe(false);
  });
});
